// Vendor lucide's per-icon metadata (categories + tags) into a single generated
// TS module that powers the interactive Icons gallery's search and category
// filters. The icon *components* ship in `lucide-react`, but that package
// carries no category/tag data — the authoritative metadata lives as one JSON
// file per icon in the lucide source repo (`icons/<name>.json`, each with
// `categories` and `tags` arrays). This is the icon analogue of
// `vendor-blocks.mjs`: fetch upstream, bake a local artifact, re-run to refresh.
//
//   node scripts/vendor-icon-meta.mjs
//
// Requires network access (Node 18+ global fetch). Authoring tool, not part of
// the build. Output is keyed by lucide's PascalCase component name so the story
// can look up `iconMeta[name]` directly against `Object.keys(icons)`.

import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const OUT = join(ROOT, "stories", "foundations", "icon-meta.ts");

const REPO = "lucide-icons/lucide";
const REF = "main";
const TREES_URL = `https://api.github.com/repos/${REPO}/git/trees/${REF}?recursive=1`;
const RAW = (path) =>
  `https://raw.githubusercontent.com/${REPO}/${REF}/${path}`;
const CONCURRENCY = 32;

/** kebab-case icon filename → lucide's PascalCase component name. */
function pascal(name) {
  return name
    .split("-")
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

/** Run an async mapper over items with a bounded worker pool, in order. */
async function mapPool(items, limit, fn) {
  const results = new Array(items.length);
  let next = 0;
  async function worker() {
    while (next < items.length) {
      const i = next++;
      results[i] = await fn(items[i], i);
    }
  }
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, worker),
  );
  return results;
}

async function fetchJson(url) {
  const res = await fetch(url, {
    headers: { "User-Agent": "mind-ui-vendor-icon-meta" },
  });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

async function main() {
  console.log(`Listing icon metadata in ${REPO}@${REF}…`);
  const tree = await fetchJson(TREES_URL);
  if (tree.truncated) {
    throw new Error(
      "Trees API response was truncated — cannot enumerate all icons.",
    );
  }
  const paths = tree.tree
    .map((t) => t.path)
    .filter((p) => p.startsWith("icons/") && p.endsWith(".json"))
    .sort();
  console.log(`Found ${paths.length} icon metadata files. Fetching…`);

  let done = 0;
  const entries = await mapPool(paths, CONCURRENCY, async (path) => {
    const slug = path.slice("icons/".length, -".json".length);
    const meta = await fetchJson(RAW(path));
    if (++done % 250 === 0) console.log(`  …${done}/${paths.length}`);
    return [
      pascal(slug),
      {
        categories: Array.isArray(meta.categories)
          ? meta.categories.sort()
          : [],
        tags: Array.isArray(meta.tags) ? meta.tags : [],
      },
    ];
  });

  // Stable, alphabetical key order so the generated file diffs cleanly.
  entries.sort((a, b) => a[0].localeCompare(b[0]));
  const map = Object.fromEntries(entries);

  const categories = [
    ...new Set(entries.flatMap(([, m]) => m.categories)),
  ].sort();
  console.log(
    `Baked ${entries.length} icons across ${categories.length} categories.`,
  );

  const body =
    `// AUTO-GENERATED by scripts/vendor-icon-meta.mjs — do not edit by hand.\n` +
    `// Per-icon { categories, tags } from ${REPO}@${REF}, keyed by lucide's\n` +
    `// PascalCase component name. Re-run the script to refresh.\n\n` +
    `export interface IconMeta {\n` +
    `  categories: string[];\n` +
    `  tags: string[];\n` +
    `}\n\n` +
    `export const iconMeta: Record<string, IconMeta> = ${JSON.stringify(map, null, 0)};\n`;
  await writeFile(OUT, body, "utf8");
  console.log(`Wrote ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
